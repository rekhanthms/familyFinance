// Bundles the daily reminder job and the app's own renewal rules into ONE file you can paste into Supabase
// (Edge Functions -> New function) or deploy with the Supabase CLI.
import { build } from 'esbuild';

await build({
  entryPoints: ['src/server/daily-reminders.ts'],
  outfile: 'supabase/functions/daily-reminders/index.ts',
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  banner: { js: '// GENERATED by `npm run build:function` from src/server/daily-reminders.ts. Do not edit by hand.' },
});
console.log('Wrote supabase/functions/daily-reminders/index.ts');
